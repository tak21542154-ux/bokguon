# 표기용 이름에서 벗겨낼 소속 접미어 (중구서울 → 중구)
_SUFFIX = re.compile(r"(서울|부산|대구|인천|광주|대전|울산|경기|강원|경남)$")


def _norm(s):
    return re.sub(r"\s+", " ", (s or "")).strip()


#  지명이 **더 긴 지명의 꼬리로 박혀 있는 경우**를 걸러낸다.
#   '남동구'의 '동구', '강서구'의 '서구', '서남구'의 '남구' 같은 것들이다.
#   한글에는 단어 경계가 없으므로, 바로 앞 글자가 한글이면 꼬리로 본다.
_HANGUL = re.compile(r"[가-힣]")
#  ⚠⚠ [라운드120] 왼쪽만 보면 실제 지명이 문자열 안에 멀쩡히 있어도, 도로/노선명이
#    그 지명으로 **시작**하기만 하면 먼저 걸려 버린다 — '동해대로'의 '동해'가 강원도
#    동해시로 잡혀 실제(경북 영덕·삼척)에서 최대 125km 벗어남을 실측 확인했다.
#    오른쪽도 시군구읍면동리 같은 행정단위 접미어로 이어지는지 봐야 한다 —
#    아니면(예: '대로'의 '대') 지명이 아니라 그 글자로 시작하는 다른 낱말이다.
_ADMIN_SUFFIX = re.compile(r"[시군구읍면동리]")

#  ⚠⚠ [라운드293] 방위+구(중구·동구·서구·남구·북구)는 "구"가 실제로 그
#    이름 자체의 행정단위 접미어라, 뒤에 다른 지명이 공백 없이 바로
#    이어져도(예: '서구청라동') 여전히 유효한 매치다. 반면 강동·구리·
#    성동·안동·양구·영동·정읍·하동처럼 **우연히** 같은 글자(동/구/리/읍)로
#    끝나는 다른 지명은 그 글자가 "단위"가 아니라 그냥 두 글자 이름의
#    일부라서, 뒤에 다른 낱말이 곧장 붙으면 실제로는 무관한 단어(예:
#    '강동원')일 위험이 여전히 있다(라운드120이 막은 바로 그 함정) — 그래서
#    이 다섯 개만 예외로 허용한다(_AMBIG 의 키를 _SUFFIX 로 벗긴 뒤 실제로
#    admin-suffix 로 끝나는 것만 골라 확인한 결과 — 그 계산에 쓰인 _AMBIG
#    자체가 아니라 이 좁은 목록만 남긴다, _AMBIG 의 '강서'·'광주'·'고성'은
#    admin-suffix 로 안 끝나 애초에 이 예외가 필요 없다).
_COMPOUND_ADMIN = {"중구", "동구", "서구", "남구", "북구"}


def _word_in(name, src):
    """name 이 src 안에 '독립된 지명'으로 들어 있는가. 있으면 매치 시작
    위치, 없으면 -1(파이썬은 -1 도 참이라 호출부는 반드시 `>= 0` 으로 본다)."""
    start = 0
    while True:
        i = src.find(name, start)
        if i < 0:
            return -1
        left_ok = i == 0 or not _HANGUL.match(src[i - 1])
        j = i + len(name)
        #  ⚠⚠ [라운드293] name 자신이 이미 완결된 복합 행정명(위 5개)이면
        #    뒤가 곧장 다른 지명으로 이어져도 유효하다 — 실측: "서구청라동"
        #    (공백 없음)이 전엔 인천 서구 매치가 거부돼 인천 광역중심(도시
        #    전체)까지 밀려났다("서구 청라동"처럼 공백이 있으면 이미 정상
        #    매치됐다 — 오직 붙여 쓴 경우만 놓쳤었다).
        right_ok = (j >= len(src) or not _HANGUL.match(src[j])
                    or _ADMIN_SUFFIX.match(src[j]) or name in _COMPOUND_ADMIN)
        if left_ok and right_ok:
            return i
        start = i + 1


#  ⚠⚠ [라운드264] _AMBIG 판정이 매치 지점 근처인지 안 보고 src 전체 어디든
#    있으면 통과시켰다 — 실측(data/partners_seed.json, "(주)KAD(KAD한국자동문)"):
#    region="경기(본사) + 부산·대구·광주 지사" 는 "광주"(부산·대구와 함께 열거된
#    지사)를 "경기도 광주시"로 오판정해 실주소(경기도 **화성시**)에서 45.4km
#    벗어났다 — 이 문자열엔 "경기"가 두 번(맨 앞 "경기(본사)", 뒤쪽 주소의
#    "경기도") 나오는데 **어느 쪽도 "광주"를 실제로 수식하지 않는다**(각자
#    다른 절에 있는 무관한 언급). 단순 "src 전체"도, "매치 앞부분 전체"도 이
#    사례를 못 걸렀다(맨 앞 "경기"가 여전히 앞부분에 있으므로) — 실제로 걸러
#    지려면 매치 **바로 앞**만 봐야 한다. 창(N)을 4~30 으로 바꿔가며 실
#    시드데이터 397곳 전수와 대조한 결과 N=6~12 구간에서만 회귀 0건으로
#    KAD 사례가 걸러지고(그다음 후보인 "화성"이 정상 매치됨) — 5 이하는
#    "부산광역시"·"대구광역시" 같은 정상 접미어(3~4자)+공백조차 못 담아
#    실제 정답 28건이 깨지고, 15 이상은 KAD의 맨 앞 "경기"가 다시 창에
#    들어와 원래 결함이 재발한다. 가운데 값(10)을 쓴다.
_AMBIG_WINDOW = 10


def resolve(region, address=""):
    """지역/주소 문자열 → (lat, lng, 출처설명). 못 찾으면 (None, None, '').

    수동 좌표는 이 함수 밖(호출자)에서 우선 적용한다.
    """
    src = _norm(region) + " " + _norm(address)
    if not src.strip():
        return None, None, ""
    #  ⚠⚠ [라운드316] 2022년부터 수원·고양·용인·창원 4개 시가 '특례시'라는
    #    공식 행정 명칭을 쓴다(예: '용인특례시') — _ADMIN_SUFFIX 는 지명 뒤
    #    **한 글자**만 보는데 '특'은 그 문자 클래스에 없어 _word_in() 이
    #    매치를 거부했고, 시군구 단위로 정확히 찾을 수 있는 주소가 훨씬
    #    부정확한 도(道) 단위 폴백까지 밀려났다(실측: '용인특례시'의 좌표
    #    오차가 정상 '용인시' 대비 약 5배(6.35km→31.4km) 벌어짐 — 운영DB
    #    협력사 #211 하우건설(주)의 실주소가 정확히 이 표기). '특례시'를
    #    '시'로 미리 바꿔 두면 이 4개 시는 물론 앞으로 추가될 특례시도
    #    한 번에 해결된다.
    src = src.replace("특례시", "시")
    # 1) 시군구 이름 매칭 — 긴 이름 먼저(예: '남양주'가 '양주'보다 먼저 잡히게)
    #
    #  ⚠ 예전에는 그냥 `disp in src` 였다. 그래서 더 긴 구 이름 **안에 박힌** 짧은 이름이
    #    먼저 잡혔다 — '인천광역시 남동구'에서 '동구'(인천)가 걸려 8.3km 떨어진 곳을 가리켰고,
    #    '부산 강서구'는 '서구'(부산)로 13.3km 어긋났다.
    #    즉 **정식 도로명주소를 정확히 적을수록 지도가 더 틀렸다.**
    #    주소 검색으로 정식 주소가 들어오기 시작하면 이 함정을 그대로 밟는다.
    #    앞 글자가 한글이면 그건 더 긴 지명의 꼬리이므로 매칭으로 치지 않는다.
    for name in sorted(GU.keys(), key=len, reverse=True):
        key = name
        # 모호 지역(중구서울 등)은 표기용 이름을 벗긴다
        disp = _SUFFIX.sub("", name)
        if not disp:
            continue
        pos = _word_in(disp, src)
        if pos >= 0:
            need = _AMBIG.get(name)
            if need:
                #  ⚠ src 전체가 아니라 매치 바로 앞 _AMBIG_WINDOW 자만 본다 —
                #    위 _AMBIG_WINDOW 주석 참고(전체를 보면 문자열 어딘가의
                #    무관한 언급도 근거로 오판정한다).
                near = src[max(0, pos - _AMBIG_WINDOW):pos]
                if not any(n in near for n in need):
                    continue
            lat, lng = GU[key]
            return lat, lng, f"{disp} 지역중심"
    # 2) 시도 폴백 — 정식명('경상북도')도 받는다. 긴 이름부터 봐야
    #    '경기도'가 '경기'보다, '광주광역시'가 '광주'보다 먼저 잡힌다.
    for full in sorted(SIDO_ALIAS.keys(), key=len, reverse=True):
        if full in src:
            short = SIDO_ALIAS[full]
            lat, lng = SIDO[short]
            return lat, lng, f"{short} 광역중심"
    for sido, (lat, lng) in SIDO.items():
        if sido in src:
            return lat, lng, f"{sido} 광역중심"
    # 3) 권역 표기('충청권' 등) — 정확도가 낮다는 걸 출처에 그대로 적는다
    for kwon, (lat, lng) in KWON.items():
        if kwon in src:
            return lat, lng, f"{kwon} 중심(개략)"
    return None, None, ""


def jitter(case_id, lat, lng, meters=350):
    """같은 지역 사건이 겹치지 않게, 사건 번호 기반의 **결정적** 미세 오프셋.

    무작위가 아니라 해시라서 같은 사건은 항상 같은 자리에 찍힌다.
    """
    if lat is None:
        return lat, lng
    h = hashlib.sha256(str(case_id).encode()).digest()
    #  ⚠⚠ [라운드293] 예전엔 dx·dy 를 각각 -1~1 로 뽑아 그대로 더해 반경이
    #    meters 가 아니라 **정사각형**(대각선 최대 meters*√2)이었다. 게다가
    #    경도에도 위도와 같은 배율을 그대로 써서, 위선이 극에 가까울수록
    #    같은 경도차가 더 짧은 실거리가 된다는 걸 안 봐 동서 방향이 실제보다
    #    덜 벌어졌다(실측: 서울 위도에서 동서:남북 = 0.79:1). 각도+반경으로
    #    뽑아 원 안에 넓이 기준으로 고르게 담고, 경도는 cos(위도)로 나눠
    #    보정한다(실측: meters=350 기준 최악 사례 447m→350.6m로 수렴).
    angle = (h[0] / 255.0) * 2 * math.pi
    radius = meters * math.sqrt(h[1] / 255.0)
    d_lat = (radius * math.cos(angle)) / 111_000.0
    d_lng = (radius * math.sin(angle)) / (111_000.0 * math.cos(math.radians(lat)))
    return lat + d_lat, lng + d_lng


def case_coords(row):
    """사건 행(dict/Row) → (lat, lng, src). 수동 좌표가 있으면 그것이 우선."""
    try:
        mlat, mlng = row["lat"], row["lng"]
    except (KeyError, IndexError, TypeError):
        mlat = mlng = None
    if mlat is not None and mlng is not None:
        #  ⚠⚠ [라운드235] 여기가 "형제(case_coords)는 이미 고쳐졌는데"(아래 partner_coords
        #    라운드216 주석)가 착각한 바로 그 자리다 — 실제로는 이 함수만 좌표가 있으면
        #    무조건 "수동"이라고 적고 있었다. geo_src 컬럼(db.py, '지역중심/수동/주소검색')이
        #    이미 있고 geocode_fill.py --target cases 가 실제로 '주소검색'을 채우는데(자동
        #    지오코딩된 사건들, test_e2e.py 도 이 값을 전제로 검증), 이 함수는 그 값을 한 번도
        #    안 읽었다. 사건 상세 지도·관제 지도·인근업체 API·협력사 진행목록이 전부 이 출처를
        #    그대로 화면에 보여준다 — 형제(partner_coords, 아래)와 같은 패턴으로 맞춘다.
        gs = row["geo_src"] if _has(row, "geo_src") else None
        return float(mlat), float(mlng), (gs or "수동")
    #  ⚠ [라운드316] 형제(partner_coords, 아래)는 이 조회를 전부 _has() 로
    #    감싸는데 여기만 "region" in row.keys() 를 직접 불렀다 — row 가
    #    None 이면(형제는 이미 _has() 의 try/except 로 안전) AttributeError
    #    로 그대로 죽는다. 지금 이 저장소의 호출부 4곳은 전부 사전에 None
    #    을 걸러내거나 예외로 감싸 실제로 도달하진 않지만, 형제와 다른
    #    패턴을 유지할 이유가 없어 통일한다.
    lat, lng, src = resolve(row["region"] if _has(row, "region") else "",
                            row["address"] if _has(row, "address") else "")
    if lat is None:
        return None, None, ""
    jlat, jlng = jitter(row["id"], lat, lng)
    return jlat, jlng, src


def haversine_km(lat1, lng1, lat2, lng2):
    """두 좌표 사이의 대권거리(km). 하나라도 좌표가 없으면 None.

    출동 배차·인근업체 정렬에 쓴다. 지역중심 좌표 기반이라 값은 **개략치**이며,
    '정확한 도로 거리'가 아니라 '누가 더 가까운가'의 순서를 잡는 용도다.
    """
    if None in (lat1, lng1, lat2, lng2):
        return None
    try:
        rlat1, rlng1, rlat2, rlng2 = map(math.radians, (lat1, lng1, lat2, lng2))
    except (TypeError, ValueError):
        return None
    dlat = rlat2 - rlat1
    dlng = rlng2 - rlng1
    a = math.sin(dlat / 2) ** 2 + math.cos(rlat1) * math.cos(rlat2) * math.sin(dlng / 2) ** 2
    return 6371.0 * 2 * math.asin(min(1.0, math.sqrt(a)))


def partner_coords(row):
    """협력사 행(dict/Row) → (lat, lng, src). 좌표 컬럼이 없어 region/address 로 해석.

    협력사는 시군구 중심좌표까지만 잡는다(정밀 주소 지오코딩 미도입 단계).
    같은 지역 협력사끼리 지도에서 안 겹치도록, 업체 id 기반 결정적 지터를 준다.
    """
    try:
        mlat = row["lat"] if "lat" in row.keys() else None
        mlng = row["lng"] if "lng" in row.keys() else None
    except (KeyError, IndexError, TypeError, AttributeError):
        mlat = mlng = None
    if mlat is not None and mlng is not None:
        #  ⚠⚠ [라운드216] 형제(case_coords, 위 298행)는 이미 "좌표가 있으면
        #    무조건 수동이라고 적었는데 이제는 주소검색이 대부분(정비 후
        #    협력사 91%)"이라며 실제 geo_src 컬럼을 읽도록 고쳐졌는데, 그
        #    근거 통계 자체가 "협력사"를 인용하면서 정작 이 함수(협력사
        #    좌표 조회)는 안 고쳐진 채 남아 있었다 — 형제 함수를 착각한
        #    것으로 보인다. 실측(2026-08-29): 활성 협력사 365곳(좌표 보유
        #    전체)이 전부 geo_src='주소검색'인데 이 함수는 100% "수동"으로
        #    돌려준다 — 지도 마커 팝업(admin.js)에서 매번 거짓 출처를 본다.
        gs = row["geo_src"] if _has(row, "geo_src") else None
        return float(mlat), float(mlng), (gs or "수동")
    reg = row["region"] if _has(row, "region") else ""
    adr = row["address"] if _has(row, "address") else ""
    lat, lng, src = resolve(reg, adr)
    if lat is None:
        return None, None, ""
    pid = row["id"] if _has(row, "id") else 0
    # 현장 지도(api_map_cases)와 '같은 자리'에 찍히도록 시드를 맞춘다(f"p{id}", 500m).
    #  안 맞추면 목록의 거리와 지도의 위치가 미세하게 어긋나 보인다.
    jlat, jlng = jitter(f"p{pid}", lat, lng, meters=500)
    return jlat, jlng, src


def _has(row, key):
    try:
        return key in row.keys()
    except (AttributeError, TypeError):
        try:
            return key in row
        except TypeError:
            return False

#  좌표 출처가 **실제 주소**에서 온 것인가. 시군구 중심(개략값)과 구분해야
#  화면이 "약 3.2km" 라고 말해도 되는지 알 수 있다.
#  기사가 0.2km 인 줄 알고 수락했다가 5km 를 이동하면 그 책임이 플랫폼으로 온다.
PRECISE_SRC = ("주소검색", "수동")


def is_precise(src):
    return (src or "") in PRECISE_SRC
