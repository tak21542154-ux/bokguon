def _period_text(days):
    """일수를 '2년'처럼 자연스럽게, 365로 안 나눠떨어지면 'N일' 그대로."""
    return f"{days // 365}년" if days and days % 365 == 0 else f"{days}일"


def privacy_body(ip_limit_enabled, max_login_fails=5, session_min=30, log_retention_days=730,
                  ai_photo_enabled=False):
    """처리방침 본문 — 켜져 있는 조치만 '시행 중' 이라고 말하고, 보안 설정 수치도
    실제 운영값을 반영한다(설정을 바꾸면 문구가 저절로 따라온다).

    ip_limit_enabled 가 False 면 IP 제한 문구만 빠지고 나머지는 그대로다.
    ai_photo_enabled 가 True 면 제6조 위탁 표에 AI 사진분석(Google Gemini) 줄이 추가된다.
    나머지 인자는 기본값이 지금까지의 고정 문구(또는 부재)와 같아, 안 넘기면 회귀 없다.
    """
    body = PRIVACY if ip_limit_enabled else PRIVACY.replace(_IP_ON, _IP_OFF, 1)
    retention = _period_text(log_retention_days)
    body = body.replace(_RETENTION_TABLE_ON, f"<td><b>{retention}</b></td>", 1)
    body = body.replace(_RETENTION_PARA_ON, f"취급자의 접속 기록을 {retention} 이상 보관", 1)
    body = body.replace(_LOGIN_LOCK_ON,
                         f"비밀번호 {max_login_fails}회 연속 오류 시 계정 잠금, "
                         f"{session_min}분 무동작 시 세션 자동 종료,", 1)
    body = body.replace(_SESSION_COOKIE_ON,
                         f"브라우저를 종료하거나 {session_min}분간 활동이 없으면 만료되며", 1)
    if ai_photo_enabled:
        body = body.replace(_ALIMTALK_ROW_TAIL,
                             _ALIMTALK_ROW_TAIL.replace("</table>", _AI_PHOTO_ROW + "</table>"), 1)
    return body


