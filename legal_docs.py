def _esc(s):
    """HTML 이스케이프.

    ⚠ 이 모듈이 만든 문자열은 템플릿에서 `{{ doc.body|safe }}` 로 **이스케이프 없이** 렌더된다.
      본문은 우리가 쓴 고정 HTML 이라 안전하지만, company_info.json 에서 읽어오는 값은
      바깥에서 들어온 데이터다. 그대로 끼워 넣으면 처리방침 페이지에 스크립트를 심을 수 있다.
      (파일을 고칠 수 있는 사람이면 서버도 만질 수 있긴 하지만, 값이 어디서 오든
       화면에 넣기 전에 이스케이프하는 것이 원칙이다)
    """
    return (str(s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;").replace("'", "&#39;"))


def _ph(key, label, hint=""):
    """확정된 값이 있으면 그대로, 없으면 눈에 띄는 '(미기재)' 표시."""
    v = (INFO.get(key) or "").strip()
    if v:
        return _esc(v)
    PENDING.append(label)
    tip = f' title="{_esc(hint)}"' if hint else ""
    return f'<span class="ph"{tip}>{_esc(label)} (미기재)</span>'


