        #    작업(2017년 값 정리)의 실패가 핵심 임무를 가로막던 것을 분리한다.
        _hist_failed += 1
        print(f"  ⚠ #{_r['id']} {_r['item']} 이력 기록 실패({type(_ex).__name__}) — 계속합니다")
