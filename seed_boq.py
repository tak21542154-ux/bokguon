def load(rows, dry=False, deactivate_demo=True):
    conn = DB.get_db()
    added = skipped = retired = 0
    majors = {r[0] for r in rows}

    try:
        #  ⚠ [라운드268] try 블록 진입 전에 있으면, 이 문장 자체가 락 경합 등으로
        #    실패할 때 아래 except의 rollback()·finally의 close() 를 둘 다 건너뛰어
        #    커넥션이 안 닫힌 채 샌다(아직 아무 행도 안 건드린 시점이라 데이터
        #    훼손 위험은 없다 — 자원누수만 막는다).
        conn.execute("BEGIN IMMEDIATE")
        for r in rows:
            major, item, spec, unit, price, src, src_date = r
            if not (src or "").strip():
                print(f"  [건너뜀] {major} · {item} — 근거가 없습니다")
                skipped += 1
                continue
            if not isinstance(price, int) or price <= 0:
                print(f"  [건너뜀] {major} · {item} — 단가가 이상합니다({price})")
                skipped += 1
                continue
            #  ⚠ [라운드268] app.py 의 등록·수정 라우트·boq_history() 는 이미
            #    근거문구를 200자에서 자르는데 이 경로만 안 잘라, standard_boq
            #    실운영 값이 이력(history) 사본보다 길어질 수 있는 유일한 통로였다
            #    (현재 ROWS 45행 실측 최대 102자라 아직 발현은 안 했다).
            src = src[:200]
            # 같은 공종·항목·규격이 이미 있으면 갱신한다(중복 적재 방지)
            #  ⚠⚠ [라운드180] ref_price 도 함께 읽는다 — 갱신 시 개정 이력의
            #    old_price 로 쓴다(바로 아래).
            ex = conn.execute(
                "SELECT id, ref_price, active FROM standard_boq WHERE major=? AND item=? "
                "  AND COALESCE(spec,'')=? AND COALESCE(is_demo,0)=0",
                (major, item, spec or "")).fetchone()
            _hrow = {"major": major, "item": item, "spec": spec, "unit": unit,
                     "ref_price": price, "price_src": src, "price_date": src_date}
            if ex:
                #  ⚠⚠ [라운드312] 아래 UPDATE 는 무조건 active=1 로 되돌린다 — 관리자가
                #    콘솔 '비활성' 버튼(app.py api_boq_delete)으로 일부러 내린 항목도
                #    재실행 한 번에 아무 흔적 없이 부활했다. PATCH 수정 라우트
                #    (api_boq_update)엔 active 를 되돌릴 방법 자체가 없어, 이 스크립트가
                #    사실상 유일한 되살리기 통로다 — 되살리기 자체는 막지 않되(그게
                #    유일한 되돌리기 수단이므로), 이 사실이 반드시 이력에 남도록 아래에서
                #    '수정'과 구분되는 별도 action 을 남긴다.
                was_inactive = (ex["active"] == 0)
                conn.execute(
                    "UPDATE standard_boq SET unit=?, ref_price=?, price_src=?, price_date=?, "
                    "       active=1, updated_at=? WHERE id=?",
                    (unit, price, src, src_date, DB.now(), ex["id"]))
                #  ⚠⚠ [라운드180] app.py 의 관리자 콘솔(추가·수정·비활성)은 표준단가가
                #    바뀔 때마다 boq_price_history 에 남기는데, 이 CLI(가장 자주
                #    쓰이는 실제 적재 경로 — 실측: activity_log 에 표준단가 적재 4회,
                #    그중 한 번이 42개 항목을 그 자리에서 덮어썼다)만 빠져 있었다.
                #    캘리브레이션(그 시점 단가 대비 낙찰가)이 그 순간부터 불가능해진다.
                #  ⚠⚠ [라운드297] 예전엔 이 이력 기록이 무조건 실행됐다 — 값이
                #    하나도 안 바뀐 재실행(운영자가 스크립트를 다시 돌리기만
                #    해도)에도 매번 "수정"(old==new) 이력이 쌓여, 진짜 개정과
                #    구별이 안 됐다(실측: 변경 없는 재실행 2회로 '수정' 44건이
                #    중복 적재됨). 값이 실제로 바뀐 경우에만 남긴다.
                if was_inactive:
                    DB.boq_history(conn, ex["id"], _hrow, action="재활성",
                                    old_price=ex["ref_price"], actor="seed_boq.py")
                    print(f"  ⚠ {major[:14]:16s} {item[:16]:18s} 비활성 상태였는데 다시 활성화됩니다"
                          f"  (콘솔에서 일부러 비활성했던 값이라면 boq_price_history 로 확인하세요)")
                elif ex["ref_price"] != price:
                    #  ⚠⚠ [라운드268] 이 UPDATE는 무조건 실행된다 — 관리자가
                    #    콘솔에서 이 항목 단가를 손으로 고쳐 뒀어도 재적재하면
                    #    조용히 이 하드코딩 값으로 되돌아간다(이력엔 남지만
                    #    그 순간 화면엔 아래 줄 전까지 아무 표시가 없었다).
                    DB.boq_history(conn, ex["id"], _hrow, action="수정",
                                    old_price=ex["ref_price"], actor="seed_boq.py")
                    print(f"  ⚠ {major[:14]:16s} {item[:16]:18s} 값 변경"
                          f" {ex['ref_price']:,}원 → {price:,}원"
                          f"  (콘솔에서 손으로 바꿔 둔 값이었다면 boq_price_history 로 확인하세요)")
            else:
                cur = conn.execute(
                    "INSERT INTO standard_boq(major,item,spec,unit,ref_price,price_src,price_date,"
                    "                         active,is_demo,created_at,updated_at) "
                    "VALUES(?,?,?,?,?,?,?,1,0,?,?)",
                    (major, item, spec or "", unit, price, src, src_date, DB.now(), DB.now()))
                DB.boq_history(conn, cur.lastrowid, _hrow, action="추가",
                                old_price=None, actor="seed_boq.py")
            added += 1
            print(f"  [적재] {major[:14]:16s} {item[:16]:18s} {price:>10,}원/{unit:2s}  ← {src[:40]}")

        if deactivate_demo:
            # 실측이 들어온 공종의 데모 값은 사용중지로 내린다.
            #  둘이 같이 보이면 어느 게 근거 있는 값인지 알 수 없다.
            for m in majors:
                #  ⚠⚠ [라운드180] 비활성 전에 대상 행을 먼저 읽어 둔다 — 일괄 UPDATE
                #    뒤에는 그 값이 뭐였는지 알 길이 없어 이력(action='비활성')을
                #    남길 수 없다. app.py 의 api_boq_delete 와 같은 원칙.
                demo_rows = conn.execute(
                    "SELECT id, item, spec, unit, ref_price, price_src, price_date "
                    "  FROM standard_boq "
                    " WHERE major=? AND COALESCE(is_demo,0)=1 AND COALESCE(active,1)=1",
                    (m,)).fetchall()
                if not demo_rows:
                    continue
                cur = conn.execute(
                    "UPDATE standard_boq SET active=0, updated_at=? "
                    " WHERE major=? AND COALESCE(is_demo,0)=1 AND COALESCE(active,1)=1",
                    (DB.now(), m))
                retired += cur.rowcount
                for dr in demo_rows:
                    DB.boq_history(conn, dr["id"], {**dict(dr), "major": m}, action="비활성",
                                    old_price=dr["ref_price"], actor="seed_boq.py")

        if dry:
            conn.rollback()
            print("\n  (미리보기라 저장하지 않았습니다)")
        else:
            DB.log(conn, "시스템", "표준단가 적재",
                   f"{added}건 적재 · 데모 {retired}건 사용중지")
            conn.commit()
            #  ⚠⚠⚠ [라운드297] 이 커밋까지가 이 함수가 하는 유일한 표준단가
            #    적재다 — sku_key(엔진 SKU 와의 연결고리)는 여기서 한 번도
            #    채워진 적이 없었다. sku_key 가 없으면 _load_price_book()
            #    (app.py, 견적엔진이 DB 단가를 읽는 유일한 경로)이 이 행을
            #    통째로 건너뛴다 — 방금 적재한 실측단가가 다음 서버 재기동
            #    (또는 manage.py migrate) 전까지 견적에 전혀 반영되지 않고,
            #    화면·도구 출력 어디에도 그 사실이 안 보인다(실측: 격리
            #    스크래치 DB에서 재기동 없이 확인 — 44건 전부 sku_key NULL,
            #    가드레일 판(2W) 등 엔진 내장값과 완전히 같은 이름·가격도
            #    price_book 에서 안 잡힘). _backfill_sku_keys() 는 NULL 인
            #    행만 채우고(운영자가 손으로 넣은 값은 안 건드림) 스스로
            #    커밋하는 멱등 함수라 여기서 바로 불러도 안전하다 —
            #    db.migrate() 가 서버 기동 때 부르는 것과 동일한 함수.
            DB._backfill_sku_keys(conn)
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
    return added, skipped, retired


